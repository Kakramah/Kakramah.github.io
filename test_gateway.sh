#!/bin/bash
# ==============================================================================
# سكريبت بوابة التسليم الآلي — مشاريع خلدون عكرمة وأنتي جرافيتي
# الدستور 3.8 — المادة §6.1
# الاستخدام: شغل السكريبت مباشرة من مجلد المشروع: ./test_gateway.sh
# ==============================================================================

fail=0
say(){ echo "$1"; }

say "========================================================"
say "  بدء الفحص الآلي لبوابة التسليم لمشاريع خلدون عكرمة (§6.1)"
say "========================================================"

# 6.1.1 — لا مسارات مطلقة
if grep -rn "/Users/\|file:///" --include="*.html" --include="*.css" --include="*.js" . 2>/dev/null; then
  say "✗ 6.1.1 مسار مطلق تم رصده في الأكواد"; fail=1
else
  say "✓ 6.1.1 المسارات نسبية ونظيفة تماماً"
fi

# 6.1.2 — لا ملفات نظام
if find . \( -name ".DS_Store" -o -name "._*" -o -name "*.bak" -o -name ".env" \) -print 2>/dev/null | grep -q . ; then
  say "✗ 6.1.2 ملفات نظام ومخلفات مؤقتة موجودة"; fail=1
else
  say "✓ 6.1.2 خلو كامل من ملفات النظام والمخلفات"
fi

# 6.1.3 — لا صور يتيمة (موجودة وغير مستعملة)
orph=0
if [ -d "images" ]; then
  for f in images/*; do
    [ -e "$f" ] || continue
    if ! grep -qr "$(basename "$f")" --include="*.html" --include="*.css" --include="*.js" . 2>/dev/null; then
      say "✗ 6.1.3 صورة يتيمة غير مستعملة: $f"; orph=1; fail=1
    fi
  done
  [ "$orph" = 0 ] && say "✓ 6.1.3 لا توجد أي صور يتيمة، كل الصور مستعملة"
fi

# 6.1.4 — لا صور مفقودة (مستدعاة وغير موجودة)
miss=0
while read -r pth; do
  [ -z "$pth" ] && continue
  if [ ! -f "$pth" ]; then
    say "✗ 6.1.4 صورة مستدعاة مفقودة: $pth"; miss=1; fail=1
  fi
done < <(grep -oh 'images/[A-Za-z0-9._-]*' -r --include="*.html" --include="*.css" . 2>/dev/null | sort -u)
[ "$miss" = 0 ] && say "✓ 6.1.4 جميع الصور المستدعاة موجودة بالفعل"

# 6.1.5 — سقوف الحجم (500KB عادية · 800KB للبطل · 4MB للمجلد)
if [ -d "images" ]; then
  while read -r f; do
    [ -z "$f" ] && continue
    kb=$(du -k "$f" | cut -f1)
    if [ "$kb" -gt 800 ]; then
      say "✗ 6.1.5 حجم ${kb}KB يتجاوز السقف الأقصى (800KB): $f"; fail=1
    elif [ "$kb" -gt 500 ]; then
      case "$f" in
        *hero*|*slide_01*|*cover*) say "✓ 6.1.5 حجم ${kb}KB مسموح لصورة البطل وحدها: $f" ;;
        *) say "✗ 6.1.5 حجم ${kb}KB يتجاوز 500KB لصورة عادية: $f"; fail=1 ;;
      esac
    fi
  done < <(find images -type f 2>/dev/null)
  
  tot=$(du -sk images 2>/dev/null | cut -f1)
  if [ "${tot:-0}" -gt 4096 ]; then
    say "✗ 6.1.5 إجمالي مجلد الصور ${tot}KB يتجاوز السقف الأقصى 4MB"; fail=1
  else
    say "✓ 6.1.5 إجمالي حجم مجلد الصور ${tot:-0}KB متوافق مع معايير الأداء"
  fi
fi

# 6.1.6 — منع الشَّخْطة والفواصل والمحرمات الترقيمية (4.12)
if grep -rn "—\|–" --include="*.html" --include="*.js" . 2>/dev/null; then
  say "✗ 4.12.1 تم رصد شَّخْطة محظورة في النصوص"; fail=1
else
  say "✓ 4.12.1 النصوص نظيفة تماماً من الشَّخْطات والمحرمات الترقيمية"
fi

# 6.1.7 — فحص التوقيع والشعار السيادي والروابط الإلزامية
if [ -f "index.html" ]; then
  grep -q "@𝓚𝓱𝓪𝓵𝓭𝓸𝓾𝓷𝓐𝓴𝓻𝓪𝓶𝓪𝓱" index.html && say "✓ التوقيع المعتمد موجود" || { say "✗ التوقيع المعتمد مفقود"; fail=1; }
  grep -q "eagle-emblem-metal.svg" index.html && say "✓ العقاب السيادي المعتمد موجود" || { say "✗ العقاب السيادي مفقود"; fail=1; }
  grep -q "966566702030" index.html && say "✓ شريحة واتساب الرسمية موجودة" || { say "✗ شريحة واتساب مفقودة"; fail=1; }
  grep -q "khaldounakramah" index.html && say "✓ شريحة إنستغرام الرسمية موجودة" || { say "✗ شريحة إنستغرام مفقودة"; fail=1; }
  grep -q "2527772c-69c7-4bd9-9319-a5b705e44bac" index.html && say "✓ مفتاح الربط السحابي Web3Forms موجود" || { say "✗ مفتاح Web3Forms مفقود"; fail=1; }
fi

# 6.1.8 — منع الركاكة اللغوية والكاف الاستعمالية المترجمة والشوائب الإملائية (§4.13)
if grep -rn "كمضاعف\|كأداة\|كمثال\|كمرجع\|كمصدر\|كمسودات\|الخطاء" --include="*.html" --include="*.js" . 2>/dev/null; then
  say "✗ 4.13 تم رصد كاف استعمالية مترجمة أو ركاكة أسلوبية محظورة"; fail=1
else
  say "✓ 4.13 صرامة لغوية ومعجمية تامة خالية من الكاف الاستعمالية المترجمة والركاكة"
fi

say "--------------------------------------------------------"
if [ "$fail" -eq 0 ]; then
  say "🎉 تهانينا! اجتاز المشروع بوابة التسليم بنجاح بنسبة 100% (fail=0)."
  say "المشروع مؤهل للعرض والنشر الرسمي."
  exit 0
else
  say "⚠️ تنبيه: رسب المشروع في بعض البنود أعلاه. يرجى تصحيحها قبل النشر."
  exit 1
fi
